#!/usr/bin/env python3
"""Generate docs/wi-outline.js — the Wisconsin outline for the Metro tab map.

One-off build step, not part of the scrape. The outline is Natural Earth's 1:10m
"admin 1 states/provinces, lakes" boundary (public domain), Wisconsin only, with
the Great Lakes clipped out so the shoreline is real. It is projected once here
(equirectangular, longitude scaled by cos 44.7°, the state's middle latitude —
indistinguishable from a conic at this size) and simplified, so the browser only
draws a path; the same projection constants go into the file so the widget can
place cities on it (widget-logic.js → projectWI()).

  curl -fsSLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces_lakes.geojson
  python scripts/build-wi-outline.py ne_10m_admin_1_states_provinces_lakes.geojson
"""
import json
import math
import sys

VIEW_W, VIEW_H = 440, 430     # viewBox; the right 60px leave room for east-shore labels
FIT_W, FIT_H, PAD = 380, 430, 14
MID_LAT = 44.7
TOLERANCE = 0.55              # px, Douglas–Peucker, in projected space
MIN_ISLAND_AREA = 6.0         # px²; drops specks that would render as dust


def simplify(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy)
    best, idx = -1.0, 0
    for i in range(1, len(points) - 1):
        x0, y0 = points[i]
        # A closed ring starts and ends on the same point: measure from that point.
        d = (abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm) if norm else math.hypot(x0 - x1, y0 - y1)
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [points[0], points[-1]]
    return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)


def area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))) / 2


def main(src):
    feats = json.load(open(src, encoding="utf-8"))["features"]
    wi = next(f for f in feats if f["properties"].get("name") == "Wisconsin"
              and f["properties"].get("iso_a2") == "US")
    geom = wi["geometry"]
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    rings = [poly[0] for poly in polys]           # outer rings; the state has no holes worth drawing

    k = math.cos(math.radians(MID_LAT))
    xs = [lon * k for r in rings for lon, _ in r]
    ys = [lat for r in rings for _, lat in r]
    min_x, max_x, min_y, max_y = min(xs), max(xs), min(ys), max(ys)
    s = min((FIT_W - 2 * PAD) / (max_x - min_x), (FIT_H - 2 * PAD) / (max_y - min_y))
    proj = {"k": round(k, 8), "minX": round(min_x, 6), "maxY": round(max_y, 6),
            "s": round(s, 6), "pad": PAD}

    def P(lon, lat):
        return (PAD + (lon * k - min_x) * s, PAD + (max_y - lat) * s)

    parts, kept = [], 0
    for r in rings:
        pts = [P(lon, lat) for lon, lat in r]
        if area(pts) < MIN_ISLAND_AREA:
            continue
        simp = simplify(pts, TOLERANCE)
        if len(simp) < 4:
            continue
        kept += len(simp)
        parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in simp) + "Z")

    out = (
        "// GENERATED by scripts/build-wi-outline.py — do not edit by hand.\n"
        "// Wisconsin outline from Natural Earth 1:10m states/provinces (lakes clipped),\n"
        "// public domain. `proj` must stay in step with the path: widget-logic.js\n"
        "// projectWI() uses it to put cities on this map.\n"
        "self.WPR_WI_OUTLINE = " + json.dumps(
            {"viewBox": [VIEW_W, VIEW_H], "proj": proj, "path": "".join(parts)},
            separators=(",", ":")) + ";\n"
    )
    open("docs/wi-outline.js", "w", encoding="utf-8", newline="\n").write(out)
    print(f"docs/wi-outline.js: {len(parts)} rings, {kept} points, {len(out)} bytes; proj={proj}")


if __name__ == "__main__":
    main(sys.argv[1])
